            payroll.AddComponent(new PayrollComponent(
                PayrollComponentType.Overtime,
                PayrollComponentCategory.Earning,
                "Overtime",
                300m,
                Guid.NewGuid()));
            
            payroll.AddComponent(new PayrollComponent(
                PayrollComponentType.LegalDeduction,
                PayrollComponentCategory.Deduction,
                "Tax",
                200m,
                Guid.NewGuid()));
            
            payroll.AddComponent(new PayrollComponent(
                PayrollComponentType.LegalDeduction,
                PayrollComponentCategory.Deduction,
                "Social Security",
                150m,
                Guid.NewGuid()));

            // Act
            payroll.MarkAsCalculated();

            // Assert
            payroll.GrossAmount.Should().Be(2300m);
            payroll.TotalDeductions.Should().Be(350m);
            payroll.NetAmount.Should().Be(1950m);
        }

        [Fact]
        public void PaymentCollections_ShouldBeReadOnly()
        {
            // Arrange
            var payroll = CreateValidPayroll();

            // Act & Assert - Verify assignable to IReadOnlyCollection
            payroll.Components.Should().BeAssignableTo<IReadOnlyCollection<PayrollComponent>>();
            payroll.MilestonePayments.Should().BeAssignableTo<IReadOnlyCollection<MilestonePayment>>();
            payroll.AguinaldoPayments.Should().BeAssignableTo<IReadOnlyCollection<AguinaldoPayment>>();
            payroll.VacationPayments.Should().BeAssignableTo<IReadOnlyCollection<VacationPayment>>();
            payroll.ProductivityPayments.Should().BeAssignableTo<IReadOnlyCollection<ProductivityPayment>>();
            payroll.OvertimePayments.Should().BeAssignableTo<IReadOnlyCollection<OvertimePayment>>();
            payroll.DeductionPayments.Should().BeAssignableTo<IReadOnlyCollection<DeductionPayment>>();
            payroll.ProjectPayments.Should().BeAssignableTo<IReadOnlyCollection<ProjectPayment>>();

            // Act & Assert
            payroll.Components.Should().NotBeOfType<List<PayrollComponent>>();
            
            // Act & Assert
            payroll.Components.Should().BeOfType<ReadOnlyCollection<PayrollComponent>>();
        }

