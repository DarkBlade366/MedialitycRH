        [Fact]
        public void Constructor_WithValidParameters_ShouldCreatePayroll()
        {
            // Arrange
            var employeeId = Guid.NewGuid();
            var periodStart = new DateTime(2024, 1, 1);
            var periodEnd = new DateTime(2024, 1, 31);

            // Act
            var payroll = new Payroll(employeeId, periodStart, periodEnd);

            // Assert
            payroll.Id.Should().NotBeEmpty();
            payroll.EmployeeId.Should().Be(employeeId);
            payroll.PeriodStart.Should().Be(periodStart);
            payroll.PeriodEnd.Should().Be(periodEnd);
            payroll.Status.Should().Be(PayrollStatus.Draft);
            payroll.GrossAmount.Should().Be(0);
            payroll.TotalDeductions.Should().Be(0);
            payroll.NetAmount.Should().Be(0);
            payroll.Components.Should().BeEmpty();
        }

