        [Fact]
        public void CompleteWorkflow_ShouldFollowCorrectStateTransitions()
        {
            // Arrange
            var payroll = CreateValidPayrollWithComponents();

            // Act & Assert - Initial state
            payroll.Status.Should().Be(PayrollStatus.Draft);

            // Act & Assert - After calculation
            payroll.MarkAsCalculated();
            payroll.Status.Should().Be(PayrollStatus.Calculated);
            payroll.GrossAmount.Should().BeGreaterThan(0);
            payroll.NetAmount.Should().BeGreaterThanOrEqualTo(0);

            // Act & Assert - After approval
            payroll.Approve();
            payroll.Status.Should().Be(PayrollStatus.Approved);

            // Act & Assert - After payment
            payroll.MarkAsPaid();
            payroll.Status.Should().Be(PayrollStatus.Paid);
        }

        [Fact]
        public void Calculation_WithMultipleComponents_ShouldCalculateCorrectAmounts()
        {
